
-- Symfony Messenger Doctrine transport
-- PostgreSQL production schema
-- Run once against the vendors-api database.

CREATE TABLE IF NOT EXISTS public.messenger_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    body TEXT NOT NULL,
    headers TEXT NOT NULL,
    queue_name VARCHAR(190) NOT NULL,
    created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    available_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    delivered_at TIMESTAMP(0) WITHOUT TIME ZONE DEFAULT NULL,

    CONSTRAINT messenger_messages_pkey PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_messenger_messages_queue_name
    ON public.messenger_messages (queue_name);

CREATE INDEX IF NOT EXISTS idx_messenger_messages_available_at
    ON public.messenger_messages (available_at);

CREATE INDEX IF NOT EXISTS idx_messenger_messages_delivered_at
    ON public.messenger_messages (delivered_at);
