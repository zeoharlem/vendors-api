<?php

declare(strict_types=1);

namespace App\Modules\Auth\Application\Services;

use App\Modules\Auth\Application\RegistrationEmailExistsException;
use App\Modules\Auth\Infrastructure\Models\Role;
use App\Modules\Auth\Infrastructure\Models\User;
use App\Shared\Database\PostgresPdoHelper;
use Phalcon\Mvc\Model\Transaction\Manager;
use RuntimeException;
use Throwable;

final class RegisterUserService
{
    public function __construct(private readonly Manager $transactionManager) {
    }

    public function register(array $data): array
    {
        $email = strtolower(trim($data['email']));

        $transaction = $this->transactionManager->get();

        try {
            // Use the connection belonging to the active transaction.
            $connection = $transaction->getConnection();
            $pdo = $connection->getInternalHandler();

            $pdoHelper = new PostgresPdoHelper($pdo);

            // Check for an existing account.
            $existingUser = User::findFirst(
                [
                    'conditions' => 'LOWER(email) = :email:',
                    'bind' => ['email' => $email],
                ]
            );

            if ($existingUser !== false && $existingUser !== null) {
                throw new RegistrationEmailExistsException(
                    'An account with this email already exists.',
                );
            }

            // Find the customer role.
            $role = Role::findFirst(
                [
                    'conditions' => 'name = :name:',
                    'bind' => ['name' => 'customer'],
                ]
            );

            if ($role === false || $role === null) {
                throw new RuntimeException(
                    'The customer role has not been seeded.',
                );
            }

            $passwordHash = password_hash(trim($data['password']), PASSWORD_DEFAULT, );

            if ($passwordHash === false || empty($passwordHash)) {
                throw new RuntimeException('Password hashing failed.');
            }

            // Insert the user and retrieve the UUID generated by PostgreSQL.
            $user = $pdoHelper->insertUser(
                [
                    'email' => $email,
                    'password_hash' => $passwordHash,
                    'first_name' => trim($data['first_name']),
                    'last_name' => trim($data['last_name']),
                    'phone' => $data['phone'] ?? null,
                ]
            );

            $userId = (string) $user['id'];

            if (!preg_match('/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i', $userId)) {
                throw new RuntimeException('PostgreSQL returned an invalid user UUID.');
            }

            // Insert the user-role relationship using the actual UUID.
            $pdoHelper->assignUserRole($userId, (int) $role->id, );

            // Commit both inserts together.
            $transaction->commit();

            return [
                'id' => $userId,
                'email' => $email,
                'first_name' => trim($data['first_name']),
                'last_name' => trim($data['last_name']),
                'status' => $user['status'] ?? null,
                'role' => 'customer',
            ];
        } catch (Throwable $exception) {
            try {
                $transaction->rollback('Registration failed.');
            } catch (Throwable) {
                // Preserve the original exception.
            }

            throw $exception;
        }
    }
}